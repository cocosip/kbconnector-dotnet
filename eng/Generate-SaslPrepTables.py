"""Generate RFC 3454 / Unicode 3.2 classification data; development only, Python 3 stdlib."""
from pathlib import Path
import stringprep

assert stringprep.unicodedata.unidata_version == "3.2.0"
tables = {
    "Unassigned": stringprep.in_table_a1,
    "MappedToNothing": stringprep.in_table_b1,
    "NonAsciiSpace": stringprep.in_table_c12,
    "Prohibited": lambda c: any(f(c) for f in (
        stringprep.in_table_c12, stringprep.in_table_c21, stringprep.in_table_c22, stringprep.in_table_c3,
        stringprep.in_table_c4, stringprep.in_table_c5, stringprep.in_table_c6,
        stringprep.in_table_c7, stringprep.in_table_c8, stringprep.in_table_c9)),
    "RandALCat": stringprep.in_table_d1,
    "LCat": stringprep.in_table_d2,
}
lines = ["// Generated by eng/Generate-SaslPrepTables.py from RFC 3454, Unicode 3.2.0.",
         "// Do not replace these frozen classifications with current-runtime Unicode categories.",
         "namespace KingbaseConnector.Protocol;", "", "internal static partial class PgSaslPrep", "{"]
for name, check in tables.items():
    ranges = []
    start = None
    for scalar in range(0x110001):
        inside = scalar < 0x110000 and check(chr(scalar))
        if inside and start is None:
            start = scalar
        elif not inside and start is not None:
            ranges.extend((start, scalar - 1))
            start = None
    lines.append(f"    static readonly int[] {name} =")
    lines.append("    [")
    for offset in range(0, len(ranges), 12):
        lines.append("        " + ", ".join(f"0x{n:X}" for n in ranges[offset:offset + 12]) + ",")
    lines.extend(("    ];", ""))
lines.append("}")
target = Path(__file__).resolve().parents[1] / "src/KingbaseConnector/Protocol/PgSaslPrep.Tables.cs"
target.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print(f"Generated {target.name} with Unicode 3.2.0 tables")
