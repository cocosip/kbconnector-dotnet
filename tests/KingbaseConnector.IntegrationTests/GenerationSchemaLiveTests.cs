using System.Data;

namespace KingbaseConnector.IntegrationTests;

public sealed class GenerationSchemaLiveTests
{
    [LiveTheory(writes: true)]
    [InlineData(false)]
    [InlineData(true)]
    public Task PgSequenceInventoryIncludesIdentityAndNeverAdvancesValues(bool async) => LiveProfile.RunPg(async (settings, token) =>
    {
        const string sequence = "kb_gen_%_'汉\"Seq";
        using var connection = new KingbaseConnection(settings.ConnectionString); await connection.OpenAsync(token);
        await Scalar(connection, "CREATE TEMP SEQUENCE " + Quote(sequence) + " AS bigint INCREMENT BY -2 MINVALUE -9223372036854775808 MAXVALUE -1 START WITH -2147483649 CACHE 17 CYCLE", token);
        await Scalar(connection, "CREATE TEMP SEQUENCE kb_gen_small AS smallint", token);
        await Scalar(connection, "CREATE TEMP SEQUENCE kb_gen_integer AS integer", token);
        await Scalar(connection, "CREATE TEMP TABLE kb_gen_owner(id bigint GENERATED ALWAYS AS IDENTITY)", token);
        var schema = await TemporarySchema(connection, token);
        using var sequences = async ? await connection.GetSchemaAsync("Sequences", [connection.Database, schema], token) : connection.GetSchema("Sequences", [connection.Database, schema]);
        Assert.Equal(4, sequences.Rows.Count);
        var row = Assert.Single(sequences.Rows.Cast<DataRow>(), item => (string)item["SEQUENCE_NAME"] == sequence);
        Assert.Equal("bigint", row["DATA_TYPE"]); Assert.Equal(64, row["NUMERIC_PRECISION"]); Assert.Equal(2, row["NUMERIC_PRECISION_RADIX"]);
        Assert.Equal(0, row["NUMERIC_SCALE"]); Assert.Equal(-2147483649L, row["START_VALUE"]); Assert.Equal(long.MinValue, row["MINIMUM_VALUE"]);
        Assert.Equal(-1L, row["MAXIMUM_VALUE"]); Assert.Equal(-2L, row["INCREMENT"]); Assert.Equal(17L, row["CACHE_SIZE"]); Assert.True((bool)row["CYCLE_OPTION"]);
        foreach (var (name, precision, maximum) in new[] { ("kb_gen_small", 16, (long)short.MaxValue), ("kb_gen_integer", 32, (long)int.MaxValue) })
        {
            var integer = Assert.Single(sequences.Rows.Cast<DataRow>(), item => (string)item["SEQUENCE_NAME"] == name);
            Assert.Equal(precision, integer["NUMERIC_PRECISION"]); Assert.Equal(maximum, integer["MAXIMUM_VALUE"]);
            Assert.Equal(1L, integer["CACHE_SIZE"]); Assert.False((bool)integer["CYCLE_OPTION"]);
        }
        var identity = Assert.IsType<string>(await Scalar(connection, "SELECT c.relname::pg_catalog.text FROM pg_catalog.pg_class c WHERE c.oid " +
            "OPERATOR(pg_catalog.=) pg_catalog.pg_get_serial_sequence('pg_temp.kb_gen_owner','id')::pg_catalog.regclass", token));
        Assert.Single(sequences.Rows.Cast<DataRow>(), item => (string)item["SEQUENCE_NAME"] == identity);
        using var literal = await connection.GetSchemaAsync("Sequences", [null, schema, sequence], token); Assert.Single(literal.Rows.Cast<DataRow>());
        using var empty = connection.GetSchema("Sequences", [null, schema, ""]); Assert.Empty(empty.Rows.Cast<DataRow>());
        using var wrongCase = connection.GetSchema("Sequences", [null, schema, sequence.ToLowerInvariant()]); Assert.Empty(wrongCase.Rows.Cast<DataRow>());
        Assert.Equal(-2147483649L, await Scalar(connection, "SELECT last_value::pg_catalog.int8 FROM pg_temp." + Quote(sequence), token));
        Assert.Equal(0, await Scalar(connection, "SELECT CASE WHEN is_called THEN 1 ELSE 0 END::pg_catalog.int4 FROM pg_temp." + Quote(sequence), token));
    });

    [LiveTheory(writes: true)]
    [InlineData(false)]
    [InlineData(true)]
    public Task PgColumnGenerationKeepsDefaultsIdentityAndExpressionsDistinct(bool async) => LiveProfile.RunPg(async (settings, token) =>
    {
        using var connection = new KingbaseConnection(settings.ConnectionString); await connection.OpenAsync(token);
        using var transaction = await connection.BeginTransactionAsync(token);
        await Scalar(connection, "CREATE TEMP SEQUENCE kb_gen_default_seq", token);
        await Scalar(connection, "CREATE TEMP TABLE kb_gen_columns(a bigint GENERATED ALWAYS AS IDENTITY " +
            "(START WITH -2147483649 INCREMENT BY -2 MINVALUE -9223372036854775808 MAXVALUE -1 CYCLE)," +
            "b bigint GENERATED BY DEFAULT AS IDENTITY,c bigint DEFAULT nextval('kb_gen_default_seq'),d int DEFAULT 42,g int GENERATED ALWAYS AS (d+1) STORED)", token);
        var schema = await TemporarySchema(connection, token);
        using var columns = async ? await connection.GetSchemaAsync("Columns", [null, schema, "kb_gen_columns"], token) : connection.GetSchema("Columns", [null, schema, "kb_gen_columns"]);
        Assert.Equal(34, columns.Columns.Count); Assert.Equal(5, columns.Rows.Count);
        var rows = columns.Rows.Cast<DataRow>().ToDictionary(row => (string)row["COLUMN_NAME"]);
        var always = rows["a"]; Assert.True((bool)always["IS_IDENTITY"]); Assert.Equal("ALWAYS", always["IDENTITY_GENERATION"]);
        Assert.Equal(-2147483649L, always["IDENTITY_START"]); Assert.Equal(-2L, always["IDENTITY_INCREMENT"]);
        Assert.Equal(-1L, always["IDENTITY_MAXIMUM"]); Assert.Equal(long.MinValue, always["IDENTITY_MINIMUM"]);
        Assert.True((bool)always["IDENTITY_CYCLE"]); Assert.Equal(DBNull.Value, always["COLUMN_DEFAULT"]);
        var byDefault = rows["b"]; Assert.True((bool)byDefault["IS_IDENTITY"]); Assert.Equal("BY DEFAULT", byDefault["IDENTITY_GENERATION"]);
        Assert.Equal(1L, byDefault["IDENTITY_START"]); Assert.Equal(long.MaxValue, byDefault["IDENTITY_MAXIMUM"]); Assert.False((bool)byDefault["IDENTITY_CYCLE"]);
        foreach (var name in new[] { "c", "d", "g" })
        {
            Assert.False((bool)rows[name]["IS_IDENTITY"]);
            foreach (var fact in new[] { "IDENTITY_GENERATION", "IDENTITY_START", "IDENTITY_INCREMENT", "IDENTITY_MAXIMUM", "IDENTITY_MINIMUM", "IDENTITY_CYCLE" })
                Assert.Equal(DBNull.Value, rows[name][fact]);
        }
        Assert.Contains("nextval", Assert.IsType<string>(rows["c"]["COLUMN_DEFAULT"])); Assert.Equal("42", rows["d"]["COLUMN_DEFAULT"]);
        foreach (var name in new[] { "a", "b", "c", "d" }) { Assert.Equal("NEVER", rows[name]["IS_GENERATED"]); Assert.Equal(DBNull.Value, rows[name]["GENERATION_EXPRESSION"]); }
        Assert.Equal("ALWAYS", rows["g"]["IS_GENERATED"]); Assert.Equal(DBNull.Value, rows["g"]["COLUMN_DEFAULT"]);
        var expression = await Scalar(connection, "SELECT pg_catalog.pg_get_expr(d.adbin,d.adrelid)::pg_catalog.text FROM pg_catalog.pg_attrdef d " +
            "JOIN pg_catalog.pg_attribute a ON a.attrelid OPERATOR(pg_catalog.=) d.adrelid AND a.attnum OPERATOR(pg_catalog.=) d.adnum " +
            "WHERE d.adrelid OPERATOR(pg_catalog.=) 'pg_temp.kb_gen_columns'::pg_catalog.regclass AND a.attname OPERATOR(pg_catalog.=) 'g'", token);
        Assert.Equal(expression, rows["g"]["GENERATION_EXPRESSION"]);
        Assert.Same(connection, transaction.Connection); await transaction.RollbackAsync(token);
        using var afterRollback = await connection.GetSchemaAsync("Columns", [null, schema, "kb_gen_columns"], token); Assert.Empty(afterRollback.Rows.Cast<DataRow>());
    });

    [LiveFact(writes: true)]
    public Task PgSequenceVisibilityRespectsLocalRoleAndRollback() => LiveProfile.RunPg(async (settings, token) =>
    {
        using var connection = new KingbaseConnection(settings.ConnectionString); await connection.OpenAsync(token);
        await Scalar(connection, "CREATE TEMP SEQUENCE kb_gen_private", token); var schema = await TemporarySchema(connection, token);
        using var visible = connection.GetSchema("Sequences", [null, schema, "kb_gen_private"]); Assert.Single(visible.Rows.Cast<DataRow>());
        using var transaction = await connection.BeginTransactionAsync(token); await Scalar(connection, "SET LOCAL ROLE pg_monitor", token);
        using var hidden = await connection.GetSchemaAsync("Sequences", [null, schema, "kb_gen_private"], token); Assert.Empty(hidden.Rows.Cast<DataRow>());
        var denied = await Assert.ThrowsAsync<KingbaseException>(() => Scalar(connection, "SELECT nextval('pg_temp.kb_gen_private')", token));
        Assert.Equal("42501", denied.SqlState); await transaction.RollbackAsync(token);
        using var recovered = await connection.GetSchemaAsync("Sequences", [null, schema, "kb_gen_private"], token); Assert.Single(recovered.Rows.Cast<DataRow>());
    });

    [LiveFact(writes: true)]
    public Task PgSequenceInventoryHidesOtherSessionsTemporarySequences() => LiveProfile.RunPg(async (settings, token) =>
    {
        using var owner = new KingbaseConnection(settings.ConnectionString); await owner.OpenAsync(token);
        await Scalar(owner, "CREATE TEMP SEQUENCE kb_gen_other", token);
        await Scalar(owner, "CREATE TEMP TABLE kb_gen_other_owner(id int GENERATED ALWAYS AS IDENTITY)", token);
        var schema = await TemporarySchema(owner, token);
        using var own = owner.GetSchema("Sequences", [null, schema]); Assert.Equal(2, own.Rows.Count);
        using var observer = new KingbaseConnection(settings.ConnectionString); await observer.OpenAsync(token);
        Assert.Equal(0, await Scalar(observer, "SELECT count(*)::pg_catalog.int4 FROM information_schema.sequences WHERE sequence_schema::pg_catalog.text OPERATOR(pg_catalog.=) @schema", token, ("schema", schema)));
        using var hidden = await observer.GetSchemaAsync("Sequences", [null, schema], token); Assert.Empty(hidden.Rows.Cast<DataRow>());
    });

    static string Quote(string value) => "\"" + value.Replace("\"", "\"\"") + "\"";
    static async Task<string> TemporarySchema(KingbaseConnection connection, CancellationToken token) => Assert.IsType<string>(await Scalar(connection,
        "SELECT nspname::pg_catalog.text FROM pg_catalog.pg_namespace WHERE oid OPERATOR(pg_catalog.=) pg_catalog.pg_my_temp_schema()", token));
    static async Task<object?> Scalar(KingbaseConnection connection, string sql, CancellationToken token, params (string Name, object Value)[] parameters)
    {
        using var command = new KingbaseCommand(sql, connection);
        foreach (var (name, value) in parameters) command.Parameters.AddWithValue(name, value);
        return await command.ExecuteScalarAsync(token);
    }
}
